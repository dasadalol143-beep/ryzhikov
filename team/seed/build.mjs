function block(rows, days, into = {}) {
  for (const f of RNP_ROWS) {
    const vals = (rows[f] || "").split(",");
    days.forEach((d, i) => {
      const v = num(vals[i]);
      if (v) (into[d] ||= {})[f] = v;
    });
  }
  return into;
}
