const num = (v) => {
  const n = Number(String(v ?? "").replace(/[\sр.₽]/g, "").replace(",", ".").replace(/^\./, ""));
  return Number.isFinite(n) ? n : 0;
};
const dayKeys = (startDay, startMonth, count) => {
  const out = [];
  let t = Date.UTC(2026, startMonth - 1, startDay);
  for (let i = 0; i < count; i++, t += 86400_000) out.push(new Date(t).toISOString().slice(0, 10));
  return out;
};

