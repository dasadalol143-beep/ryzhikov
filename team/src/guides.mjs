const ROLE_NAME = { owner: "Собственник", rop: "РОП", mop: "МОП (диагност)", lidorub: "Лидоруб" };

export function guideParts(user) {
  const role = user.role || "mop";
  const first = (user.name || "").split(" ")[0];
  const body = { lidorub: LIDORUB, mop: MOP, rop: ROP, owner: [...ROP, OWNER_EXTRA] }[role] || MOP;
  return [INTRO(first, ROLE_NAME[role] || role), ...body, BOT];
}

// Шлёт инструкцию человеку. Кнопка «Открыть приложение» — на последнем сообщении.
export async function sendGuide(tg, user, appUrl) {
  const parts = guideParts(user);
  for (let i = 0; i < parts.length; i++) {
    const markup = i === parts.length - 1 && appUrl ? { inline_keyboard: [[{ text: "Открыть приложение", web_app: { url: appUrl } }]] } : undefined;
    await tg.sendMessage(user.id, parts[i], markup);
  }
}
