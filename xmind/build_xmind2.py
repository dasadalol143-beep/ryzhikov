def md(n, depth=0):
    L=[]
    if depth==0: L.append("# "+n["title"].replace("\n"," — "))
    elif depth<=3: L.append("#"*(depth+1)+" "+n["title"])
    else: L.append("    "*(depth-4)+"- "+n["title"])
    note=n.get("notes",{}).get("plain",{}).get("content")
    if note and depth>=1:
        pre=("    "*(depth-3)) if depth>=4 else ""
        L.append(pre+"- _"+note+"_")
    for ch in n.get("children",{}).get("attached",[]): L+=md(ch,depth+1)
    return L
