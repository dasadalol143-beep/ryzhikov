# ---- запасной .md (с заметками как под-пунктами курсивом) ----
def md(n, depth=0):
    lines = []
    if depth == 0:
        lines.append("# " + n["title"])
    elif depth <= 3:
        lines.append("#" * (depth + 1) + " " + n["title"])
    else:
        lines.append("    " * (depth - 4) + "- " + n["title"])
    note = n.get("notes", {}).get("plain", {}).get("content")
    if note and depth >= 1:
        prefix = ("    " * (depth - 3)) if depth >= 4 else ""
        lines.append(prefix + "- _" + note + "_")
    for ch in n.get("children", {}).get("attached", []):
        lines += md(ch, depth + 1)
    return lines
